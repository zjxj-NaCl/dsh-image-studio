/** Deterministic, dependency-free build for these explicitly supported modules. */
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const root = fileURLToPath(new URL('.', import.meta.url))
const names = ['src/index.js', 'src/image-api.js', 'src/comfy.js', 'src/tool.js', 'src/studio-model.js', 'src/client.js', 'src/model-config.js', 'src/conversation-host.js', 'src/bridge.js']
const data = Object.fromEntries(names.map(name => [name, readFileSync(join(root, name), 'utf8')]))
const hash = createHash('sha256').update(names.map(name => name + '\n' + data[name]).join('\n')).digest('hex')
const header = '// Generated by build.mjs; edit src, not lib. Source SHA256: ' + hash + '\n'

function declarations(source) {
  const exports = [...source.matchAll(/^export (?:async )?(?:const|function|class) (\w+)/gm)].map(m => m[1])
  const body = source.replace(/^export (?=(?:async )?(?:const|function|class) )/gm, '')
  if (/^\s*(?:import|export)\b/m.test(body)) throw new Error('Unsupported module syntax: extend the build contract explicitly')
  return { body, exports }
}

const model = declarations(data['src/studio-model.js'])
const config = declarations(data['src/model-config.js'])
let clientSource = data['src/client.js']
for (const [line, expected] of [["import * as React from 'react'", 'React'], ["import * as Model from './studio-model.js'", 'Model'], ["import { CONFIG_STYLES, LLMConfigPanel, ModelConfigPanel, StudioAssistant, chooseWorkflow, refreshConfig, refreshWorkflows } from './model-config.js'", 'ModelConfig']]) {
  if (!clientSource.includes(line)) throw new Error('Missing expected client import: ' + expected)
  clientSource = clientSource.replace(line, '')
}
const client = declarations(clientSource)
const generated = header + `window.__ModuleLoader__.load({id:'dsh-image-studio',factory:(require)=>{\nconst React=require('react');\nconst Model=(()=>{\n${model.body}\nreturn {${model.exports.join(',')}};})();\n${config.body}\n${client.body}\nreturn {${client.exports.join(',')}};\n}});\n`
new Function('window', generated) // Validate the whole packaged client before writing either output.
const host = header + data['src/index.js']
const check = process.argv.includes('--check')
for (const [name, contents] of [['lib/index.js', host], ['lib/image-api.js', header + data['src/image-api.js']], ['lib/comfy.js', header + data['src/comfy.js']], ['lib/tool.js', header + data['src/tool.js']], ['lib/client.js', generated], ['lib/conversation-host.js', header + data['src/conversation-host.js']], ['lib/bridge.js', data['src/bridge.js']]]) {
  if (check) {
    if (readFileSync(join(root, name), 'utf8') !== contents) throw new Error(name + ' is stale; run npm run build')
  } else writeFileSync(join(root, name), contents, 'utf8')
}
console.log(check ? 'Build outputs match source.' : 'Host and Client built: ' + hash.slice(0, 12))
